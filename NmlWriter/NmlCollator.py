import logging
import re
import shutil
from pathlib import Path

from Badge import BadgeRegistry
from .NmlBadgeWriter import NmlBadgeWriter

logger = logging.getLogger(__name__)


class NmlCollator:
    def __init__(self):
        pass

    def collate(self, files, project_name, custom_nml_folder=None, project_path=None):
        self.output_file = f"Build/{project_name}.nml"
        custom_nml_output = Path("WorkingData") / project_name / "custom_nml"
        custom_nml_files = []

        if custom_nml_folder:
            custom_nml_source = Path(custom_nml_folder)
            if custom_nml_source.is_dir():
                for source_file in sorted(path for path in custom_nml_source.rglob("*") if path.is_file()):
                    destination_file = custom_nml_output / source_file.relative_to(custom_nml_source)
                    destination_file.parent.mkdir(parents=True, exist_ok=True)
                    self._copy_custom_nml_file(source_file, destination_file, project_path)
                    custom_nml_files.append(destination_file)
                logger.info(f"Copied {len(custom_nml_files)} custom NML file(s) to {custom_nml_output}")
            else:
                logger.debug(f"No custom NML folder found at '{custom_nml_source}'.")

        with open(self.output_file, "w", encoding="utf-8") as f:
            f.write("// !!!!! Warning, auto generated file. Do not edit this file. !!!!!\n")
            f.write("// This .nml file is auto-generated from the individual .gnml files for each variant and the GRF.\n")
            f.write("// Do not edit this file, it will be over-written during the next build.\n")

            # Split GRF header from vehicle variant files
            grf_files = [file for file in files if "GRF.gnml" in str(file)]
            other_files = [file for file in files if "GRF.gnml" not in str(file)]

            # 1. Collated GRF block
            for file in grf_files:
                logger.debug(f"Collating GRF file: {file}")
                with open(file, "r", encoding="utf-8") as infile:
                    f.write(f"\n\n// File: {file}\n")
                    f.write(infile.read())

            # 2. Collate project-provided NML files after GRF definitions and parameters.
            for file in custom_nml_files:
                logger.debug(f"Collating custom NML file: {file}")
                with open(file, "r", encoding="utf-8") as infile:
                    f.write(f"\n\n// File: {file}\n")
                    f.write(infile.read())
                    f.write("\n\n")

            # 3. Write badgetable and FEAT_BADGES item definitions
            NmlBadgeWriter().write_all(f)

            # 4. Collated vehicle item files
            for file in other_files:
                logger.debug(f"Collating variant file: {file}")
                with open(file, "r", encoding="utf-8") as infile:
                    f.write(f"\n\n// File: {file}\n")
                    f.write(infile.read())

        logger.info(f"Collated NML written to {self.output_file}")
        return self.output_file

    def _copy_custom_nml_file(self, source_file, destination_file, project_path):
        shutil.copy2(source_file, destination_file)
        if source_file.suffix.lower() not in {".nml", ".pnml", ".gnml"} or project_path is None:
            return

        content = source_file.read_text(encoding="utf-8")
        path_pattern = re.compile(r"([\"'])([^\"'\n]+)\1")

        def make_absolute(match):
            raw_path = match.group(2)
            path = Path(raw_path)
            if path.is_absolute():
                return match.group(0)

            source_relative_path = (source_file.parent / path).resolve()
            project_relative_path = (Path(project_path) / path).resolve()
            resolved_path = next(
                (candidate for candidate in (source_relative_path, project_relative_path) if candidate.is_file()),
                None,
            )
            if resolved_path is None:
                return match.group(0)
            return f"{match.group(1)}{resolved_path}{match.group(1)}"

        rewritten_content = path_pattern.sub(make_absolute, content)
        destination_file.write_text(rewritten_content, encoding="utf-8")