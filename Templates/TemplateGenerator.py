from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from .BoundingBox import BoundingBox
from .TemplateDefinition import TemplateDefinition
from .TemplateLoaderNML import TemplateLoaderNML


# The measured BRTrains length-8 corrections, expressed in NML/template pixels.
# The same per-view correction is applied to every modern train length.  Legacy
# templates remain byte-for-byte recoverable in archive/ and are intentionally
# not adjusted by this rule.
MODERN_TRAIN_OFFSET_CORRECTIONS = (
    (0, -1),   # N
    (-2, 1),   # NE
    (5, 0),    # E
    (0, 0),    # SE
    (0, 6),    # S
    (-2, 1),   # SW
    (-1, 0),   # W
    (0, 0),    # NW
)


class TemplateGenerator:
    """Recreate the generated NML template catalogue during each build."""

    def __init__(self, archive_dir: str | Path):
        self.archive_dir = Path(archive_dir)

    def definitions(self) -> list[TemplateDefinition]:
        definitions = TemplateLoaderNML().read_folder(str(self.archive_dir))
        return [self._correct(definition) for definition in definitions]

    def render(self) -> str:
        lines = [
            "// !!!!! Warning, auto generated file. Do not edit this file. !!!!!",
            "// Generated from Templates/archive by TemplateGenerator.",
        ]
        for definition in self.definitions():
            lines.extend(self._render_definition(definition))
            lines.append("")
            if self._is_modern_train(definition):
                lines.extend(self._render_definition(self._generic_definition(definition)))
                lines.append("")
        return "\n".join(lines)

    @staticmethod
    def _generic_definition(definition: TemplateDefinition) -> TemplateDefinition:
        boxes = [
            replace(box, offset_x=box.offset_x - (2 if index in (1, 3, 5, 7) else 0),
                    offset_y=box.offset_y - (1 if index in (1, 3, 5, 7) else 0))
            for index, box in enumerate(definition.bounding_boxes)
        ]
        return replace(definition, name=f"{definition.name}_generic", bounding_boxes=boxes)

    def _correct(self, definition: TemplateDefinition) -> TemplateDefinition:
        if not self._is_modern_train(definition):
            return definition

        boxes = []
        for index, box in enumerate(definition.bounding_boxes):
            dx, dy = MODERN_TRAIN_OFFSET_CORRECTIONS[index]
            boxes.append(replace(box, offset_x=box.offset_x + dx, offset_y=box.offset_y + dy))
        return replace(definition, bounding_boxes=boxes)

    @staticmethod
    def _is_modern_train(definition: TemplateDefinition) -> bool:
        return (
            definition.name.startswith("tmpl_train_")
            and not definition.legacy
            and len(definition.bounding_boxes) == 8
        )

    @staticmethod
    def _render_definition(definition: TemplateDefinition) -> list[str]:
        lines = [f"template {definition.name}(x, y)", "{"]
        for box in definition.bounding_boxes:
            flags = "|".join(box.flags)
            offset_x = str(box.offset_x)
            offset_y = str(box.offset_y)
            fields = [
                f"x+{box.left_x}",
                f"y+{box.upper_y}",
                str(box.width),
                str(box.height),
                offset_x,
                offset_y,
            ]
            if flags or box.filename or box.mask:
                fields.append(flags or "0")
            if box.filename or box.mask:
                fields.append(f'"{box.filename or ""}"')
            if box.mask:
                fields.append(f'"{box.mask}"')
            lines.append("    [" + ", ".join(fields) + "]")
        lines.append("}")
        return lines
